class FakeClock:
    def __init__(self, now: dt.datetime = BASE_NOW) -> None:
        self.now = now

    def __call__(self) -> dt.datetime:
        return self.now

    def advance(self, **kwargs) -> dt.datetime:
        self.now += dt.timedelta(**kwargs)
        return self.now


def vision_estimate(**overrides) -> MealVisionEstimate:
    def ranged(value: float) -> RangedValue:
        return RangedValue(estimate=value, low=value * 0.8, high=value * 1.25)

    base = dict(
        is_food=True, not_food_reason=None,
        items=[FoodItem(name="grilled chicken", portion_description="one palm-sized piece",
                        estimated_weight_g=140.0, visibility="visible", confidence="medium", notes=None),
               FoodItem(name="cooking oil", portion_description="about a tablespoon",
                        estimated_weight_g=12.0, visibility="assumed_hidden", confidence="low",
                        notes="not visible; typical for pan frying")],
        totals=Totals(carbs_g=ranged(48.4), protein_g=ranged(36.2), fat_g=ranged(18.3),
                      fiber_g=ranged(6.1), calories_kcal=ranged(503.0)),
        overall_confidence="medium",
        scene=Scene(multiple_plates=False, contains_beverage=False, packaged_food=False,
                    hidden_fats_likely=True, portion_reference_visible=True),
        assumptions=["Chicken was pan fried in oil."],
        ambiguities=["Rice portion partly hidden."],
        clarification_questions=["Was the rice white or brown?"],
    )
    base.update(overrides)
    return MealVisionEstimate(**base)


class FakeVision:
    """Stands in for the OpenAI adapter. Records every image it is given."""

    def __init__(self) -> None:
        self.calls: list[bytes] = []
        self.estimate = vision_estimate()
        self.error: Exception | None = None

    def analyze(self, jpeg: bytes) -> VisionResult:
        self.calls.append(jpeg)
        if self.error is not None:
            raise self.error
        return VisionResult(estimate=self.estimate, model_requested="test-vision-model",
                            model_reported="test-vision-model-2026-01-01",
                            usage={"input_tokens": 900, "output_tokens": 210, "total_tokens": 1110})


@dataclasses.dataclass
class Harness:
    client: TestClient
    ctx: V2Context
    clock: FakeClock
    vision: FakeVision
    v1_app: object
    image_dir: pathlib.Path

    def register(self, email: str = "a@example.com", *, consent: bool = True,
                 personalization: bool = True, timezone: str = TZ) -> dict:
        response = self.client.post("/api/v2/auth/register", json={
            "email": email, "password": PASSWORD, "timezone": timezone})
        assert response.status_code == 201, response.text
        headers = {"Authorization": f"Bearer {response.json()['session']['token']}"}
        if consent:
            self.consent(headers, "necessary_processing")
            if personalization:
                self.consent(headers, "personalization_history")
        return headers

    def consent(self, headers: dict, consent_type: str, state: str = "granted") -> None:
        response = self.client.put(f"/api/v2/consents/{consent_type}", headers=headers,
                                   json={"state": state})
        assert response.status_code == 200, response.text

    def push_cgm(self, headers: dict, start: dt.datetime, end: dt.datetime, *,
                 source: str = "demo", device_id: str = "sim-1", step_minutes: int = 5,
                 unit: str = "mg/dL", offset: float = 0.0, meals: list[dt.datetime] | None = None) -> dict:
        readings, moment = [], start
        while moment <= end:
            value = synthetic_glucose(moment, meals or []) + offset
            if unit == "mmol/L":
                value = value / 18.016
            readings.append({"observed_at": moment.isoformat(), "value": round(value, 3), "unit": unit})
            moment += dt.timedelta(minutes=step_minutes)
        summary = None
        for index in range(0, len(readings), 4000):
            response = self.client.post("/api/v2/cgm/readings", headers=headers, json={
                "source": source, "device_id": device_id, "readings": readings[index:index + 4000]})
            assert response.status_code == 200, response.text
            summary = response.json()
        return summary

    def meal(self, headers: dict, occurred_at: dt.datetime, macros: dict | None = None) -> str:
        response = self.client.post("/api/v2/meals", headers=headers, json={
            "occurred_at": occurred_at.isoformat(), "macros": macros or MEAL})
        assert response.status_code == 201, response.text
        return response.json()["meal_id"]

    def predict(self, headers: dict, meal_id: str, **body):
        return self.client.post(f"/api/v2/meals/{meal_id}/predict", headers=headers, json=body or None)


def synthetic_glucose(moment: dt.datetime, meals: list[dt.datetime]) -> float:
    """Deterministic, obviously artificial glucose: a daily wave plus a bump per meal."""
    minutes = moment.hour * 60 + moment.minute
    value = 102.0 + 9.0 * math.sin(2 * math.pi * minutes / 1440.0)
    for meal in meals:
        elapsed = (moment - meal).total_seconds() / 60.0
        if 0 < elapsed < 180:
            value += 48.0 * math.exp(-((elapsed - 55.0) / 34.0) ** 2)
    return value


def jpeg_bytes(size=(640, 480), color=(180, 120, 60), exif: bool = False) -> bytes:
    image = Image.new("RGB", size, color)
    buffer = io.BytesIO()
    kwargs = {}
    if exif:
        data = Image.Exif()
        data[0x010F] = "TestCameraMaker"      # Make
        data[0x8825] = {2: (40.0, 26.0, 46.0), 4: (79.0, 58.0, 56.0)}  # GPS IFD
        kwargs["exif"] = data
    image.save(buffer, format="JPEG", **kwargs)
    return buffer.getvalue()


