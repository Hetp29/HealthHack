def build_harness(tmp_path, v1_settings, **setting_overrides) -> Harness:
    clock = FakeClock()
    vision = FakeVision()
    v1_app = create_app(v1_settings)
    # Set GLUCOTWIN_TEST_APP_DB_URL to run this whole suite against another database
    # (e.g. a scratch PostgreSQL). Its schema is dropped and recreated for every test,
    # so NEVER point it at a database that holds anything.
    external = os.environ.get("GLUCOTWIN_TEST_APP_DB_URL")
    settings = V2Settings(
        app_db_url=external or f"sqlite:///{tmp_path / 'app.db'}",
        cors_origins=["http://localhost:5173"],
        image_dir=tmp_path / "images",
        **setting_overrides,
    )
    engine = make_engine(settings.app_db_url)
    if external:
        from backend.app.v2.db import tables

        tables.metadata.drop_all(engine)
    create_all(engine)
    ctx = V2Context(settings=settings, engine=engine, prediction_service=v1_app.state.service,
                    image_store=LocalImageStore(settings.image_dir), vision=vision, clock=clock)
    client = TestClient(PlatformApp(v1_app, create_v2_app(ctx)))
    return Harness(client=client, ctx=ctx, clock=clock, vision=vision, v1_app=v1_app,
                   image_dir=settings.image_dir)


def seed_scored_meals(h: Harness, headers: dict, count: int, *, spacing_hours: float = 5.0,
                      cgm_days: int = 3, push: bool = True) -> list[tuple[str, dt.datetime]]:
    """`count` past meals, each forecast (retrospectively) so it has an episode.

    Meals are `spacing_hours` apart, the most recent ending well before `now`, so every
    response window is complete. They are scored the next time anything asks.
    Returns `(meal_id, occurred_at)` oldest first.
    """
    now = h.clock.now
    times = [now - dt.timedelta(hours=spacing_hours * (i + 1)) for i in range(count)][::-1]
    if push:
        h.push_cgm(headers, now - dt.timedelta(days=cgm_days), now, meals=times)
    seeded = []
    for index, moment in enumerate(times):
        macros = {**MEAL, "carbs_g": 30.0 + 12.0 * index, "calories_kcal": 380.0 + 48.0 * index}
        meal_id = h.meal(headers, moment, macros)
        response = h.predict(headers, meal_id)
        assert response.status_code == 200, response.text
        seeded.append((meal_id, moment))
    return seeded


def snapshot_features(h: Harness, prediction_id: str) -> dict:
    from sqlalchemy import select

    from backend.app.v2.db import tables as t

    with h.ctx.engine.connect() as conn:
        row = conn.execute(
            select(t.feature_snapshots.c.feature_names, t.feature_snapshots.c.feature_values)
            .select_from(t.feature_snapshots.join(t.predictions))
            .where(t.predictions.c.prediction_id == prediction_id)).one()
    return dict(zip(row[0], row[1]))
